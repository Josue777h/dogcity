CREATE TABLE IF NOT EXISTS public.negocios (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id uuid,
  nombre text NOT NULL UNIQUE, nombre_visible text NOT NULL,
  telefono text, whatsapp_contacto text, direccion text,
  theme_color text DEFAULT '#EA580C', color_secundario text DEFAULT '#FFF7ED',
  instagram text, facebook text, tiktok text, footer_message text,
  pago_banco text, pago_alias text, metodos_pago jsonb DEFAULT '["efectivo","transferencia"]'::jsonb,
  lat numeric, lng numeric, tipo_domicilio text DEFAULT 'automatico',
  costo_por_km numeric DEFAULT 0, domicilio_minimo numeric DEFAULT 0,
  precio_domicilio numeric DEFAULT 0, logo_url text,
  business_type varchar(50) NOT NULL DEFAULT 'general',
  created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now()
