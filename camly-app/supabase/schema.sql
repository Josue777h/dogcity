CREATE OR REPLACE FUNCTION public.fn_sync_pedido_status() RETURNS trigger
LANGUAGE plpgsql SET search_path=public,pg_temp AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN NEW.estado:=NEW.status;
  ELSIF NEW.estado IS DISTINCT FROM OLD.estado THEN NEW.status:=NEW.estado; END IF;
  IF NEW.items IS DISTINCT FROM OLD.items AND (NEW.productos IS NULL OR NEW.productos='[]'::jsonb) THEN NEW.productos:=NEW.items;
  ELSIF NEW.productos IS DISTINCT FROM OLD.productos AND (NEW.items IS NULL OR NEW.items='[]'::jsonb) THEN NEW.items:=NEW.productos; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_sync_pedido_status ON public.pedidos;
CREATE TRIGGER trg_sync_pedido_status BEFORE INSERT OR UPDATE ON public.pedidos
FOR EACH ROW EXECUTE FUNCTION public.fn_sync_pedido_status();

CREATE OR REPLACE FUNCTION public.guard_customer_order_cancellation() RETURNS trigger
LANGUAGE plpgsql SET search_path=public,pg_temp AS $$
BEGIN
  IF NEW.cancelled_by='customer' AND NEW.status='CANCELADO' THEN
    IF OLD.status NOT IN ('COTIZACION_ENVIADA','CONFIRMADO_GRACIA') OR OLD.estado NOT IN ('COTIZACION_ENVIADA','CONFIRMADO_GRACIA') THEN
      RAISE EXCEPTION 'El pedido ya no se puede cancelar desde el seguimiento';
    END IF;
    IF OLD.status='CONFIRMADO_GRACIA' AND (OLD.confirmed_at IS NULL OR OLD.confirmed_at < now()-interval '60 seconds') THEN
      RAISE EXCEPTION 'Terminó el tiempo para deshacer el pedido';
    END IF;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_guard_customer_cancel ON public.pedidos;
CREATE TRIGGER trg_guard_customer_cancel BEFORE UPDATE ON public.pedidos
FOR EACH ROW EXECUTE FUNCTION public.guard_customer_order_cancellation();

