CREATE TABLE IF NOT EXISTS public.productos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  negocio_id uuid NOT NULL REFERENCES public.negocios(id) ON DELETE CASCADE,
  categoria_id bigint REFERENCES public.categorias(id) ON DELETE SET NULL,
  nombre text NOT NULL, precio numeric NOT NULL DEFAULT 0, descripcion text DEFAULT '',
  unidad text DEFAULT 'unidad', imagen text DEFAULT '', categoria text DEFAULT '',
  disponible boolean DEFAULT true, created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.domiciliarios (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  negocio_id uuid NOT NULL REFERENCES public.negocios(id) ON DELETE CASCADE,
  nombre text NOT NULL, telefono text NOT NULL, activo boolean NOT NULL DEFAULT true,
  created_at timestamptz DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.suscripciones (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  negocio_id uuid NOT NULL REFERENCES public.negocios(id) ON DELETE CASCADE,
  plan text NOT NULL DEFAULT 'pro', estado text NOT NULL DEFAULT 'trial', es_trial boolean NOT NULL DEFAULT true,
  fecha_inicio timestamptz DEFAULT now(), fecha_fin timestamptz,
  created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now(),
  CONSTRAINT uq_suscripciones_negocio UNIQUE (negocio_id)
);
CREATE TABLE IF NOT EXISTS public.pedidos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  negocio_id uuid NOT NULL REFERENCES public.negocios(id) ON DELETE CASCADE,
  domiciliario_id uuid REFERENCES public.domiciliarios(id) ON DELETE SET NULL,
  nombre text NOT NULL, telefono text NOT NULL, direccion text, ubicacion_link text, comentarios text DEFAULT '',
  total numeric NOT NULL DEFAULT 0, domicilio_costo numeric DEFAULT 0, distancia_km numeric,
  items jsonb DEFAULT '[]'::jsonb, productos jsonb DEFAULT '[]'::jsonb,
  estado text DEFAULT 'nuevo', status text DEFAULT 'nuevo', entrega_metodo text DEFAULT 'envio',
  pago_metodo text DEFAULT 'efectivo', token text,
  delivery_type varchar(50) NOT NULL DEFAULT 'fixed', delivery_fee numeric(12,2) NOT NULL DEFAULT 0,
  subtotal_amount numeric(12,2) NOT NULL DEFAULT 0, total_amount numeric(12,2) NOT NULL DEFAULT 0,
  cancellation_reason text, cancelled_by varchar(20), payment_method varchar(50) DEFAULT 'cash',
  payment_receipt_url text, payment_status varchar(30) NOT NULL DEFAULT 'pending',
  quote_sent_at timestamptz, confirmed_at timestamptz,
  created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now()
